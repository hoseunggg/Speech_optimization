class LossCSVCallback(TrainerCallback):
    def __init__(self, csv_path):
        self.csv_path = csv_path
        self.rows = []
        self.t0 = None

    def on_train_begin(self, args, state, control, **kwargs):
        self.t0 = time.time()

    def on_log(self, args, state, control, logs=None, **kwargs):
        if logs and "loss" in logs:
            row = {
                "step": state.global_step,
                "loss": float(logs["loss"]),
                "elapsed_sec": time.time() - self.t0,
            }
            self.rows.append(row)
            pd.DataFrame(self.rows).to_csv(self.csv_path, index=False)


class OptimizerTrainer(Trainer):
    def __init__(self, optimizer_name, lr, weight_decay, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.optimizer_name = optimizer_name
        self._lr = lr
        self._wd = weight_decay

    def create_optimizer(self):
        if self.optimizer is None:
            self.optimizer = make_optimizer(
                self.optimizer_name,
                self.model.parameters(),
                lr=self._lr,
                wd=self._wd,
            )
        return self.optimizer

