def duration_sec(audio_obj):
    if isinstance(audio_obj, dict) and audio_obj.get("duration") is not None:
        return float(audio_obj["duration"])
    return len(audio_obj["array"]) / audio_obj["sampling_rate"]

def take_by_hours(streaming_ds, hours=3.0, max_items=None):
    max_sec = hours * 3600.0
    total = 0.0
    rows = []
    for ex in streaming_ds:
        a = ex["audio"]
        dur = duration_sec(a)
        if total + dur > max_sec:
            break
        rows.append(ex)
        total += dur
        if max_items is not None and len(rows) >= max_items:
            break
    return Dataset.from_list(rows)

def take_n(streaming_ds, n):
    rows = []
    for i, ex in enumerate(streaming_ds):
        if i >= n:
            break
        rows.append(ex)
    return Dataset.from_list(rows)

