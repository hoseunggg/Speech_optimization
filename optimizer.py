class TinyMLP(nn.Module):
    def __init__(self, d):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(d, 256),
            nn.ReLU(),
            nn.Linear(256, 2),
        )
    def forward(self, x):
        return self.net(x)

def make_optimizer(name, params, lr, wd):
    name = name.lower()
    if name == "adam":   return optim.Adam(params, lr=lr, weight_decay=wd)
    if name == "adamw":  return optim.AdamW(params, lr=lr, weight_decay=wd)
    if name == "lion":   return optx.Lion(params, lr=lr, weight_decay=wd)
    if name == "shampoo":return optx.Shampoo(params, lr=lr, weight_decay=wd)
    if name == "muon":   return optx.Muon(params, lr=lr, weight_decay=wd)
    raise ValueError(name)

@torch.no_grad()
def eval_acc(model, loader):
    model.eval()
    correct, total = 0, 0
    for xb, yb in loader:
        xb, yb = xb.to(device), yb.to(device)
        logits = model(xb)
        pred = logits.argmax(dim=-1)
        correct += (pred == yb).sum().item()
        total += yb.numel()
    return correct / total

def run_experiment(optimizer_name, lr, batch_size=256, max_steps=300, wd=0.0, time_budget_sec=None):
    model = TinyMLP(D).to(device)
    opt = make_optimizer(optimizer_name, model.parameters(), lr=lr, wd=wd)

    train_loader = torch.utils.data.DataLoader(train_ds, batch_size=batch_size, shuffle=True, num_workers=0)
    test_loader  = torch.utils.data.DataLoader(test_ds,  batch_size=batch_size, shuffle=False, num_workers=0)

    t0 = time.time()
    steps = 0
    last_loss = None

    model.train()
    it = iter(train_loader)
    while steps < max_steps:
        if time_budget_sec is not None and (time.time() - t0) >= time_budget_sec:
            break

        try:
            xb, yb = next(it)
        except StopIteration:
            it = iter(train_loader)
            xb, yb = next(it)

        xb, yb = xb.to(device), yb.to(device)

        opt.zero_grad(set_to_none=True)
        logits = model(xb)
        loss = F.cross_entropy(logits, yb)
        loss.backward()
        opt.step()

        last_loss = float(loss.item())
        steps += 1

    runtime = time.time() - t0
    acc = eval_acc(model, test_loader)

    # "학습이 실제로 달라졌는지" 체크용: 마지막 레이어 평균
    with torch.no_grad():
        wmean = model.net[-1].weight.float().mean().item()

    # cleanup
    del model, opt
    gc.collect()
    torch.cuda.empty_cache()

    return {
        "optimizer": optimizer_name,
        "lr": lr,
        "batch_size": batch_size,
        "max_steps_req": max_steps,
        "train_steps": steps,
        "train_runtime_sec": runtime,
        "last_loss": last_loss,
        "test_acc": acc,
        "last_layer_weight_mean": wmean,
    }

